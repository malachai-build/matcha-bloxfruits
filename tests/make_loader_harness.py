"""Generate a self-contained Luau harness for loader.lua's failure paths.

    python -I tests/make_loader_harness.py [out.luau | -]    (default: stdout)

The harness embeds the current loader.lua, stubs the Matcha globals it uses
(httpget, warn, task.wait, mouse1release, setrobloxinput) and emulates
Matcha's loadstring (a syntax error gives a function that only prints when
called). It runs the loader against fake chunk bodies in five scenarios and
asserts what the cleanup did: all chunks fine; a runtime error in 20_ui2; a
syntax error in 30_esp; a truncated 40_combat download; a failure while an
older copy of the script is still running (the older copy must be left
alone). It needs a Luau runtime (`luau out.luau`); none is installed on the
build machine, so check.sh only syntax-checks the generated file with
luau-lsp. See README / CHANGES (Oct 15 2026).
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
loader = (root / "loader.lua").read_text(encoding="utf-8").replace("\r\n", "\n")
assert "]==]" not in loader

HARNESS = r'''-- Generated by tests/make_loader_harness.py: loader.lua failure-path harness.
-- Runs with a plain Luau runtime only (not in Matcha). Prints PASS/FAIL lines.
local LOADER_SOURCE = [==[
@@LOADER@@
]==]

local log = {}
local function note(text) log[#log + 1] = text end
local function has(prefix)
    for _, line in ipairs(log) do
        if string.sub(line, 1, #prefix) == prefix then return true end
    end
    return false
end
local function count(prefix)
    local n = 0
    for _, line in ipairs(log) do
        if string.sub(line, 1, #prefix) == prefix then n = n + 1 end
    end
    return n
end

-- Matcha stubs.
warn = function(...) note("warn " .. table.concat({ ... }, " ")) end
mouse1release = function() note("mouse1release") end
setrobloxinput = function(value) note("setrobloxinput " .. tostring(value)) end
task = { wait = function() end }
local realLoadstring = loadstring
-- Matcha: loadstring never returns nil; a syntax error prints when called.
loadstring = function(source, chunkName)
    local fn, err = realLoadstring(source, chunkName)
    if fn then return fn end
    return function() note("console " .. tostring(err)) end
end

local BODIES = {}
httpget = function(url)
    local name = string.match(url, "([%w_]+)%.lua$")
    return BODIES[name] or ""
end

local NAMES = { "00_core", "10_ui", "20_ui2", "30_esp", "40_combat",
    "50_farms", "60_afq", "70_misc", "80_misc2", "90_main" }
local function chunk(name, body, noEnd)
    local text = "-- @chunk " .. name .. "\n"
        .. "local LACED_LOAD = type(_G.__lacedLoad) == \"table\" and _G.__lacedLoad or nil\n"
        .. "if LACED_LOAD and type(LACED_LOAD.started) == \"table\" then LACED_LOAD.started[\"" .. name .. "\"] = true end\n"
        .. string.rep("-- padding so the body is longer than 100 bytes\n", 3)
        .. (body or "") .. "\n"
    if not noEnd then
        text = text .. "if LACED_LOAD and type(LACED_LOAD.done) == \"table\" then LACED_LOAD.done[\"" .. name .. "\"] = true end\n"
    end
    return text
end
-- 00_core stand-in: a run-bound state and an idempotent shutdownScript.
local CORE = [[
do
    local state = { unloaded = false }
    SCRIPT_STATE = state
    function alive() return not state.unloaded end
    function shutdownScript(reason)
        if state.shutdownStarted then return end
        state.shutdownStarted = true
        state.unloaded = true
        warn("shutdown " .. tostring(reason))
    end
end
]]

local function reset(overrides)
    log = {}
    _G.__lacedLoad = nil
    for _, name in ipairs(NAMES) do BODIES[name] = chunk(name, name == "00_core" and CORE or "") end
    for name, body in pairs(overrides or {}) do BODIES[name] = body end
end
local function runLoader()
    local fn = realLoadstring(LOADER_SOURCE, "loader")
    return pcall(fn)
end

local failures = 0
local function check(name, condition)
    if condition then print("PASS " .. name) else failures = failures + 1; print("FAIL " .. name); for _, l in ipairs(log) do print("    " .. l) end end
end

-- A: every chunk loads.
reset()
shutdownScript = nil; SCRIPT_STATE = nil
local okA = runLoader()
check("A all chunks load, no cleanup", okA and has("warn [laced.club] all 10 chunks loaded") and not has("warn shutdown"))

-- B: runtime error in 20_ui2 -> this run's shutdown("loader"), loader raises.
shutdownScript = nil; SCRIPT_STATE = nil
reset({ ["20_ui2"] = chunk("20_ui2", "local t = nil; local x = t.field") })
local okB, errB = runLoader()
check("B runtime error: loader raises", not okB and string.find(tostring(errB), "20_ui2", 1, true) ~= nil)
check("B runtime error: shutdown(loader) ran once", count("warn shutdown loader") == 1)
check("B runtime error: later chunks did not run", BODIES["30_esp"] ~= nil and not has("warn [laced.club] loading 30_esp"))

-- C: syntax error in 30_esp (Matcha: the call only prints) -> never started.
shutdownScript = nil; SCRIPT_STATE = nil
reset({ ["30_esp"] = chunk("30_esp", "local x = = 1") })
local okC, errC = runLoader()
check("C syntax error detected by the start marker", not okC and string.find(tostring(errC), "never started", 1, true) ~= nil)
check("C syntax error: shutdown(loader) ran", has("warn shutdown loader"))

-- D: truncated 40_combat download (no end marker in the body).
shutdownScript = nil; SCRIPT_STATE = nil
reset({ ["40_combat"] = chunk("40_combat", "", true) })
local okD, errD = runLoader()
check("D truncated download rejected before running", not okD and string.find(tostring(errD), "truncated", 1, true) ~= nil)
check("D truncated download: shutdown(loader) ran", has("warn shutdown loader"))

-- E: an older copy is running and the new load fails inside 00_core before
-- shutdownScript exists: the older copy must not be shut down.
local olderState = { unloaded = false }
SCRIPT_STATE = olderState
shutdownScript = function(reason) warn("older shutdown " .. tostring(reason)) end
reset({ ["00_core"] = chunk("00_core", "local t = nil; local x = t.field") })
local okE = runLoader()
check("E failure in 00_core leaves an older running copy alone",
    not okE and not has("warn older shutdown") and olderState.unloaded == false and has("mouse1release"))

print(failures .. " harness check(s) failed")
'''

text = HARNESS.replace("@@LOADER@@", loader)
if len(sys.argv) > 1 and sys.argv[1] != "-":
    out = pathlib.Path(sys.argv[1])
    out.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", out)
else:
    sys.stdout.write(text)
